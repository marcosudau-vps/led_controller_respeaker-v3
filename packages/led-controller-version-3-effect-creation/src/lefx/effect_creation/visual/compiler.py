"""One source generator for previews and independent LEFX V3 packages."""

from dataclasses import dataclass
import hashlib
import inspect
from pathlib import Path
from pprint import pformat
import tempfile
import types

from lefx.effect_creation import pack_effect, validate_effect_source
from lefx.engine import EffectLibrary
from lefx.sdk import RenderContext, resolve_configuration

from . import kernel
from .blocks import BLOCKS, DesignError
from .model import find, objects, property_specs, validate
from .persistence import atomic_write, canonical, digest

COMMON_FUNCTIONS = (kernel.values_for, kernel.elements_in, kernel.shift_limits,
                    kernel.compose_pixel, kernel.render_scene)
DEFINITIONS = {"state": "StateDefinition", "controlled_overlay": "ControlledOverlayDefinition",
               "timed_overlay": "TimedOverlayDefinition", "event": "EventDefinition"}


def _parameter(name, kind, default, minimum=None, maximum=None):
    types_by_kind = {"float": "FLOAT", "int": "INT", "color": "COLOR",
                     "bool": "BOOL", "duration": "DURATION_MS"}
    args = [f"name={name!r}", f"type=ParamType.{types_by_kind[kind]}", f"default={default!r}"]
    if minimum is not None:
        args.append(f"minimum={minimum!r}")
    if maximum is not None:
        args.append(f"maximum={maximum!r}")
    return f"{name!r}: ParamDefinition({', '.join(args)})"


def source_code(document):
    scene = validate(document)
    effect = scene["effect"]
    used = sorted({item["type"] for item in objects(scene) if item.get("type") in BLOCKS})
    animated = bool(scene["animations"])
    directional = any(item["type"] == "rotation" for item in scene["animations"])
    parameters = [_parameter("color", "color", "#FFFFFF"), _parameter("brightness", "float", 1.0, 0.0, 1.0)]
    if animated:
        parameters.append(_parameter("speed", "float", 1.0, 0.01, 100.0))
    if directional:
        parameters.append(_parameter("reverse", "bool", False))
    if effect["kind"] in ("event", "timed_overlay"):
        parameters.append(_parameter("duration_ms", "duration", effect["duration_ms"], 1, 600000))
    for entry in scene["exposures"]:
        item = find(scene, entry["target"])
        spec = property_specs(item)[entry["property"]]
        parameters.append(_parameter(entry["name"], spec.kind, item["properties"][entry["property"]],
                                     spec.minimum, spec.maximum))
    definition_class = DEFINITIONS[effect["kind"]]
    functions = [BLOCKS[name].evaluate for name in used] + list(COMMON_FUNCTIONS)
    header = (
        f"# Generated by LEFX Studio; revision {scene['revision']}; design sha256 {digest(scene)}\n"
        "# Runtime dependencies: LEFX V3 SDK and Python standard library only.\n"
        "import math\nimport colorsys\n"
        f"from lefx.sdk import BaseEffect, RenderContext, ColorModel, CompositionMode, ParamDefinition, ParamType, parse_color, {definition_class}\n\n"
    )
    code = header + "\n\n".join(inspect.getsource(function).strip() for function in functions)
    for category, variable in (("element", "ELEMENTS"), ("animation", "ANIMATIONS")):
        entries = [f"{name!r}: {BLOCKS[name].evaluate.__name__}" for name in used if BLOCKS[name].category == category]
        code += f"\n\n{variable} = {{{', '.join(entries)}}}"
    code += f"\n\nSCENE = {pformat(scene, sort_dicts=True, width=100)}\n\n"
    code += (
        "class VisualEffect(BaseEffect):\n"
        f"    definition = {definition_class}(\n"
        f"        id={effect['id']!r}, title={effect['title']!r}, description={effect['description']!r},\n"
        f"        color_model=ColorModel.MONO, composition=CompositionMode.{effect['composition'].upper()},\n"
        f"        animated={animated!r}, directional={directional!r},\n"
        f"        parameter_schema={{{', '.join(parameters)}}},\n"
        "    )\n\n"
        "    def render(self, ctx: RenderContext) -> list[int | None]:\n"
        "        return render_scene(SCENE, ctx)\n"
    )
    return code


@dataclass(frozen=True)
class CompiledDesign:
    revision: int
    design_hash: str
    source: str
    effect_class: type

    def render(self, elapsed, led_count=12, params=None):
        definition = self.effect_class.get_definition()
        configuration = resolve_configuration(definition, overrides=params or {})
        context = RenderContext(now=float(elapsed), started_at=0.0, led_count=led_count,
                                definition=definition, params=configuration, inputs={})
        return self.effect_class().render(context)


def compile_design(document):
    snapshot = validate(document)
    source = source_code(snapshot)
    module = types.ModuleType("_lefx_visual_preview")
    exec(compile(source, "<lefx-visual-design>", "exec"), module.__dict__)
    return CompiledDesign(snapshot["revision"], digest(snapshot), source, module.VisualEffect)


def write_source(document, directory):
    """Write a new source directory; existing directories are never overwritten."""
    snapshot = validate(document)
    target = Path(directory)
    target.mkdir(parents=True, exist_ok=False)
    generated = source_code(snapshot)
    (target / "effect.py").write_text(generated, encoding="utf-8")
    (target / "effect.yaml").write_text(
        f"source_id: {snapshot['effect']['source_id']}\nentry_file: effect.py\nentry_class: VisualEffect\n",
        encoding="utf-8")
    (target / "studio").mkdir()
    (target / "studio" / "project.json").write_bytes(canonical(snapshot))
    report = validate_effect_source(target)
    if not report.ok:
        raise DesignError("Generierter Effekt ist ungültig: " + "; ".join(report.errors))
    return target


CHECK_TIMES = (0.0, 0.125, 0.5, 1.0, 1.75, 2.5, 4.0, 7.25)
UNCHANGED = "Die Zieldatei wurde nicht verändert."


def export_package(document, path, *, led_count=12, times=CHECK_TIMES):
    """Stage, pack and check a current snapshot; only a package that passed replaces ``path``.

    The check is :func:`verify_package` — the engine's own loader and a frame
    comparison with the preview — run on the staged candidate, not on the
    written file. A package the loader refuses, or whose frames disagree with
    the preview, raises :class:`DesignError` and leaves ``path`` exactly as it
    was: an older valid package there survives a failed export.
    """
    snapshot = validate(document)
    with tempfile.TemporaryDirectory(prefix="lefx-visual-build-") as temporary:
        root = Path(temporary)
        source = write_source(snapshot, root / "source")
        package = root / "effect.lefx"
        report = pack_effect(source, package)
        try:
            check = verify_package(package, snapshot, times=times, led_count=led_count)
        except DesignError as exc:
            raise DesignError(f"{exc} {UNCHANGED}") from exc
        except Exception as exc:
            raise DesignError(f"Die Prüfung des Pakets ist fehlgeschlagen: {exc} {UNCHANGED}") from exc
        if check["mismatches"]:
            raise DesignError(
                f"Export abgebrochen: {len(check['mismatches'])} von {check['compared']} Zeitpunkten "
                f"des Pakets weichen von der Vorschau ab. {UNCHANGED}")
        data = package.read_bytes()
    target = atomic_write(path, data)
    return {**report, "path": str(target), "revision": snapshot["revision"],
            "design_hash": digest(snapshot), "sha256": hashlib.sha256(data).hexdigest(), "check": check}


def verify_package(path, document, *, times=CHECK_TIMES, led_count=12):
    """Load an exported package with the engine's own loader; compare its frames.

    The package is read exactly as a service would read it — through an
    :class:`EffectLibrary` — and the effect it yields is rendered at ``times``
    next to the preview compiled from ``document``. Raises if the loader refuses.
    """
    snapshot = validate(document)
    library = EffectLibrary(search_paths=[])
    try:
        entry = library.add_source(path)
        if entry.error:
            raise DesignError(f"Der LEFX-Loader lehnt das Paket ab: {entry.error}")
        loaded = library.registry.get(snapshot["effect"]["id"]).effect_class
        exported = CompiledDesign(snapshot["revision"], digest(snapshot), "", loaded)
        preview = compile_design(snapshot)
        mismatches = [moment for moment in times
                      if exported.render(moment, led_count) != preview.render(moment, led_count)]
    finally:
        library.close()
    return {"effect_id": snapshot["effect"]["id"], "compared": len(times), "mismatches": mismatches}
